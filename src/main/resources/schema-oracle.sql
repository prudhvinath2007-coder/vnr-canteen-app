-- ====================================================================
-- College Canteen Food Ordering & Management System
-- Oracle Database Schema (DDL)
-- Compatible with Oracle 12c, 19c, 21c, 23ai & Oracle XE
-- ====================================================================

-- 1. USERS Table (Customers / Students and Canteen Staff/Admin)
CREATE TABLE USERS (
    USER_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    PHONE VARCHAR2(20),
    ROLL_NUMBER VARCHAR2(50),
    DEPARTMENT VARCHAR2(50),
    PASSWORD VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(30) NOT NULL, -- 'STUDENT', 'CANTEEN_ADMIN'
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. CATEGORIES Table (Breakfast, Lunch, Snacks, Beverages, etc.)
CREATE TABLE CATEGORIES (
    CATEGORY_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(255),
    DISPLAY_ORDER NUMBER DEFAULT 0,
    ICON VARCHAR2(50) DEFAULT 'bi-cup-hot'
);

-- 3. MENU_ITEMS Table
CREATE TABLE MENU_ITEMS (
    ITEM_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CATEGORY_ID NUMBER NOT NULL,
    NAME VARCHAR2(150) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    PRICE NUMBER(10, 2) NOT NULL,
    IMAGE_URL VARCHAR2(500),
    IS_VEG NUMBER(1) DEFAULT 1 CHECK (IS_VEG IN (0, 1)),
    IS_AVAILABLE NUMBER(1) DEFAULT 1 CHECK (IS_AVAILABLE IN (0, 1)),
    PREP_TIME_MINS NUMBER DEFAULT 10,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_MENU_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID) ON DELETE CASCADE
);

-- 4. ORDERS Table
CREATE TABLE ORDERS (
    ORDER_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORDER_NUMBER VARCHAR2(50) UNIQUE NOT NULL, -- e.g. ORD-20261011-001
    TOKEN_NUMBER NUMBER NOT NULL,              -- e.g. Token #101
    CUSTOMER_NAME VARCHAR2(100) NOT NULL,
    STUDENT_ROLL_NO VARCHAR2(50),
    PHONE VARCHAR2(20),
    TOTAL_AMOUNT NUMBER(10, 2) NOT NULL,
    ORDER_STATUS VARCHAR2(30) DEFAULT 'ORDERED' NOT NULL, -- 'ORDERED', 'PREPARING', 'READY_TO_COLLECT', 'DELIVERED', 'CANCELLED'
    PAYMENT_STATUS VARCHAR2(30) DEFAULT 'PENDING' NOT NULL, -- 'PENDING', 'PAID', 'REFUNDED'
    SPECIAL_INSTRUCTIONS VARCHAR2(500),
    ORDER_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PREPARATION_START_TIME TIMESTAMP,
    READY_TIME TIMESTAMP,
    DELIVERY_TIME TIMESTAMP
);

-- 5. ORDER_ITEMS Table
CREATE TABLE ORDER_ITEMS (
    ORDER_ITEM_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORDER_ID NUMBER NOT NULL,
    ITEM_ID NUMBER NOT NULL,
    ITEM_NAME VARCHAR2(150) NOT NULL,
    QUANTITY NUMBER NOT NULL CHECK (QUANTITY > 0),
    UNIT_PRICE NUMBER(10, 2) NOT NULL,
    SUBTOTAL NUMBER(10, 2) NOT NULL,
    CONSTRAINT FK_ORDER_ITEMS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ORDER_ITEMS_MENU FOREIGN KEY (ITEM_ID) REFERENCES MENU_ITEMS(ITEM_ID)
);

-- 6. PAYMENTS Table (UPI details, transaction reference, timestamp)
CREATE TABLE PAYMENTS (
    PAYMENT_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORDER_ID NUMBER NOT NULL UNIQUE,
    PAYMENT_METHOD VARCHAR2(50) DEFAULT 'UPI' NOT NULL,
    UPI_ID VARCHAR2(100),
    TRANSACTION_REF_NO VARCHAR2(100), -- UTR or Reference Number
    AMOUNT NUMBER(10, 2) NOT NULL,
    PAYMENT_STATUS VARCHAR2(30) DEFAULT 'SUCCESS' NOT NULL,
    PAYMENT_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PAYMENTS_ORDER FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID) ON DELETE CASCADE
);

-- 7. NOTIFICATIONS Table (Live Student Notifications)
CREATE TABLE NOTIFICATIONS (
    NOTIFICATION_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    STUDENT_ROLL_NO VARCHAR2(50) NOT NULL,
    TITLE VARCHAR2(150) NOT NULL,
    MESSAGE VARCHAR2(500) NOT NULL,
    TYPE VARCHAR2(30) DEFAULT 'INFO', -- 'ORDERED', 'PREPARING', 'READY', 'DELIVERED', 'CANCELLED'
    ORDER_NUMBER VARCHAR2(50),
    TOKEN_NUMBER NUMBER,
    IS_READ NUMBER(1) DEFAULT 0 CHECK (IS_READ IN (0, 1)),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Indexes for fast order querying and dashboard performance
CREATE INDEX IDX_ORDERS_STATUS ON ORDERS(ORDER_STATUS);
CREATE INDEX IDX_ORDERS_ORDER_TIME ON ORDERS(ORDER_TIME);
CREATE INDEX IDX_ORDERS_TOKEN ON ORDERS(TOKEN_NUMBER);
CREATE INDEX IDX_MENU_CATEGORY ON MENU_ITEMS(CATEGORY_ID);
CREATE INDEX IDX_NOTIF_STUDENT ON NOTIFICATIONS(STUDENT_ROLL_NO);
CREATE INDEX IDX_NOTIF_CREATED ON NOTIFICATIONS(CREATED_AT);
